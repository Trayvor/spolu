#!/usr/bin/env bash
# Tests for caddy_redirects in scripts/lib.sh (the redirects.caddy that deploy/Caddyfile imports).
# With Docker available it also validates deploy/Caddyfile with the Caddy image of
# deploy/docker-compose.yml, once with old domains and once without.
set -u
root="$(cd "$(dirname "$0")/../.." && pwd)"
# shellcheck source=scripts/lib.sh
source "$root/scripts/lib.sh"
fail=0
d="$(mktemp -d)"
trap 'rm -rf "$d"' EXIT

check() { # name, expected, actual
  if [[ "$2" != "$3" ]]; then echo "FAIL $1"; echo " expected: $2"; echo " actual:   $3"; fail=1; fi
}
header='# Generated by scripts/deploy.sh from REDIRECT_DOMAINS (scripts/lib.sh caddy_redirects).'

out="$(unset REDIRECT_DOMAINS; DOMAIN=help.example.com caddy_redirects)"
check "unset: comments only, no site block" "$(printf '%s\n# No old domains to redirect.' "$header")" "$out"

out="$(DOMAIN=help.example.com REDIRECT_DOMAINS='  ' caddy_redirects)"
check "blank: comments only, no site block" "$(printf '%s\n# No old domains to redirect.' "$header")" "$out"

out="$(DOMAIN=help.example.com REDIRECT_DOMAINS='spolu.example.com  old.example.org' caddy_redirects)"
# shellcheck disable=SC2016 # Caddy placeholders
expected="$(printf '%s\nspolu.example.com old.example.org {\n\tredir https://{$DOMAIN}{uri} permanent\n}' "$header")"
check "old domains: one block redirecting each to DOMAIN" "$expected" "$out"

for bad in 'Spolu.example.com' 'http://spolu.example.com' 'spolu.example.com/x' 'localhost' '*.example.com' 'a{b}.example.com'; do
  if DOMAIN=help.example.com REDIRECT_DOMAINS="$bad" caddy_redirects >/dev/null 2>&1; then
    echo "FAIL invalid domain accepted: $bad"; fail=1
  fi
done
if DOMAIN=help.example.com REDIRECT_DOMAINS='spolu.example.com help.example.com' caddy_redirects >/dev/null 2>&1; then
  echo "FAIL DOMAIN itself accepted as an old domain"; fail=1
fi

# The real Caddyfile with the generated file, if Docker runs here.
if command -v docker >/dev/null 2>&1 && docker info >/dev/null 2>&1; then
  caddy_image="$(sed -n 's/^ *image: \(caddy:.*\)$/\1/p' "$root/deploy/docker-compose.yml")"
  cp "$root/deploy/Caddyfile" "$d/Caddyfile"
  validate() { # name, REDIRECT_DOMAINS
    DOMAIN=help.example.com REDIRECT_DOMAINS="$2" caddy_redirects > "$d/redirects.caddy"
    if ! docker run --rm -v "$d:/etc/caddy:ro" -e DOMAIN=help.example.com "$caddy_image" \
      caddy validate --config /etc/caddy/Caddyfile > "$d/validate.log" 2>&1; then
      echo "FAIL caddy validate ($1)"; cat "$d/validate.log"; fail=1
    fi
  }
  validate "no old domains" ""
  validate "two old domains" "spolu.example.com old.example.org"
else
  echo "caddy-redirects.test.sh: Docker not available, skipped caddy validate"
fi

[[ $fail -eq 0 ]] && echo "caddy-redirects.test.sh: all passed"
exit $fail
